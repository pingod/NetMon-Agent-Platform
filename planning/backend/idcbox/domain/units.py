#: 端口速度（Mbps）—— 用于推荐线缆类型，不作为端口身份
SPEED_1G: Final[int] = 1_000
SPEED_10G: Final[int] = 10_000
SPEED_25G: Final[int] = 25_000
SPEED_40G: Final[int] = 40_000
SPEED_100G: Final[int] = 100_000


# --------------------------------------------------------------------------
# 跨机柜 N 公式的系数（N = 0 if Δrow==0 else n_base*Δrow + n_extra）
# --------------------------------------------------------------------------
#: 每一排（平面图行）的等效柜宽系数，实测 4
N_ROW_COEF: Final[int] = 4
#: 固定余量，实测 4（跨一排即 8，跨两排 12，跨三排 16）
N_ROW_EXTRA: Final[int] = 4


# --------------------------------------------------------------------------
# 机房平面图几何（403 / 404 两个房间）
# --------------------------------------------------------------------------
#: 403 房间机柜列坐标范围（含端点），列 38 为排端走线架入口
ROOM_403_COLS: Final[tuple[int, int]] = (23, 38)
#: 404 房间机柜列坐标范围（含端点），列 18 为排端走线架入口
ROOM_404_COLS: Final[tuple[int, int]] = (3, 18)

#: 平面图机柜行起始行号（行 3 是第 1 条通道的北侧）
FLOOR_FIRST_ROW: Final[int] = 3
#: 每条通道占两行（北侧 / 南侧），故行号步长 2
FLOOR_ROW_STRIDE: Final[int] = 2

#: 通道号 → 房间号。通道 1..7 属 403，8..14 属 404。
ROOM_OF_CHANNEL: Final[dict[int, str]] = {
    **{k: "403" for k in range(1, 8)},
    **{k: "404" for k in range(8, 15)},
}

#: 房间 → 机柜列坐标最大值（= 排端走线架入口列，CMAX）。可被规则文件覆盖。
DEFAULT_CMAX_BY_ROOM: Final[dict[str, int]] = {"403": 38, "404": 18}


# --------------------------------------------------------------------------
# 机内线缆 Q 的默认查表（按线缆类型）
# --------------------------------------------------------------------------
#: RJ45 固定 7 米（硬规则，实测 254/254）；LC-LC 与 MPO 均为 5 米
DEFAULT_IN_RACK_LEN_BY_TYPE: Final[dict[str, int]] = {
    "RJ45": 7,
    "LC-LC": 5,
    "MPO": 5,
}


# --------------------------------------------------------------------------
# 长度档位
# --------------------------------------------------------------------------
#: 展示档位（9 档，含 35）
LADDER_TIERS: Final[tuple[int, ...]] = (5, 7, 10, 15, 20, 25, 30, 35, 40)
#: 采购档位（8 档，35 不单独采购，合并到 40）
PURCHASE_TIERS: Final[tuple[int, ...]] = (5, 7, 10, 15, 20, 25, 30, 40)

#: 原 IFS 公式无 else 分支，S > 37 时 Excel 返回 #N/A，系统必须显式处理
LADDER_MAX_INPUT: Final[float] = 37.0


# --------------------------------------------------------------------------
# 端口槽位相位（模块 8 模型，实测 112/112 组成立）
# --------------------------------------------------------------------------
#: 计算节点第一个 2U 槽位的起始 U
SLOT_BASE_U: Final[int] = 3
#: 槽位间距（每 4U 一个 2U 槽位）
SLOT_PITCH_U: Final[int] = 4
#: 每机柜槽位数（8 个 2U 槽位 = 32U，剩 10U 给 ToR）
SLOT_COUNT: Final[int] = 8


# --------------------------------------------------------------------------
# 数值口径
# --------------------------------------------------------------------------
#: Excel 只保留 15 位有效数字，Python 双精度直接算会与 Excel 存值不一致
EXCEL_SIGNIFICANT_DIGITS: Final[int] = 15
#: 浮点比较容差（禁止字符串比较）
FLOAT_REL_TOL: Final[float] = 1e-12


# --------------------------------------------------------------------------
# 端口角色与网络平面
# --------------------------------------------------------------------------
#: 端口角色枚举的合法值（实测 5 类端口号段完全不同，故必须一等建模）
PORT_ROLES: Final[tuple[str, ...]] = (
    "downlink",   # 下联服务器
    "uplink",     # 上联核心
    "peer_link",  # 接入交换机之间横向互联（M-LAG/stack）
    "stack",      # 堆叠/管理
    "mgmt",       # 管理口
    "spare",      # 保留
    "unknown",
)

#: 五个物理网络平面（来自「服务器接线示意」sheet）
NET_PLANES: Final[tuple[str, ...]] = (
    "OOB_MGMT",   # 物理网1 带外管理网
    "INBAND_MGMT",  # 物理网2 带内管理网络
    "CONTROL",    # 物理网3 控制网
    "BUSINESS",   # 物理网4 业务网
    "STORAGE",    # 物理网5 存储网
)
