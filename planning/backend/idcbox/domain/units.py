"""几何与算法常量的唯一中心。

铁律（架构 §2.1）：本模块**不含任何公式**，只放常量与单位换算。
`0.72` 这类由公式推导出的魔数**禁止**出现在这里 —— 它必须由
`cable_length.formulas.r_inter_rack()` 从 CABINET_PITCH_M × CABLE_SLACK_RATIO 算出，
否则「公式只活一次」的合同就破了。
"""

from __future__ import annotations

from typing import Final

# --------------------------------------------------------------------------
# 单位与物理常量
# --------------------------------------------------------------------------
MM_PER_M: Final[int] = 1000

#: 机柜标准宽度（mm），即机柜中心间距 600mm
CABINET_PITCH_MM: Final[int] = 600
CABINET_PITCH_M: Final[float] = 0.6

#: 标准机柜 U 数
